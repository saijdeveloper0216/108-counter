/** Generates Purnima & Amavasya dates + tithi times (IST / New Delhi) from Drik Panchang. Run: node scripts/generate-lunar-days.mjs */

import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const START_YEAR = 2025;
const END_YEAR = 2035;

const MONTHS = {
  January: 1,
  February: 2,
  March: 3,
  April: 4,
  May: 5,
  June: 6,
  July: 7,
  August: 8,
  September: 9,
  October: 10,
  November: 11,
  December: 12,
};

const MONTH_ABBR = {
  Jan: 1,
  Feb: 2,
  Mar: 3,
  Apr: 4,
  May: 5,
  Jun: 6,
  Jul: 7,
  Aug: 8,
  Sep: 9,
  Oct: 10,
  Nov: 11,
  Dec: 12,
};

function parseGreg(text) {
  const match = text.match(/^([A-Za-z]+) (\d{1,2}), (\d{4})/);
  if (!match) {
    return null;
  }
  const month = String(MONTHS[match[1]]).padStart(2, '0');
  const day = match[2].padStart(2, '0');
  return `${match[3]}-${month}-${day}`;
}

function stripHtml(text) {
  return text.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
}

function resolveTimingYear(observanceDate, timingMonth) {
  const [year, observanceMonth] = observanceDate.split('-').map(Number);
  if (timingMonth === 12 && observanceMonth === 1) {
    return year - 1;
  }
  if (timingMonth === 1 && observanceMonth === 12) {
    return year + 1;
  }
  return year;
}

function parseTiming(text, observanceDate) {
  const match = text.match(/(\d{1,2}:\d{2}(?::\d{2})?) ([AP]M), ([A-Za-z]+) (\d{1,2})/);
  if (!match) {
    return null;
  }

  const monthNumber = MONTH_ABBR[match[3]];
  if (!monthNumber) {
    return null;
  }

  const year = resolveTimingYear(observanceDate, monthNumber);
  const date = `${year}-${String(monthNumber).padStart(2, '0')}-${match[4].padStart(2, '0')}`;
  const time = `${match[1]} ${match[2]}`;

  return {
    date,
    time,
    label: `${time}, ${match[3]} ${match[4]}`,
  };
}

function dedupePurnimaEntries(entries) {
  const sorted = [...entries].sort((a, b) => a.date.localeCompare(b.date));
  const out = [];
  for (const entry of sorted) {
    if (out.length === 0) {
      out.push(entry);
      continue;
    }
    const previous = out[out.length - 1];
    const diffDays = (Date.parse(entry.date) - Date.parse(previous.date)) / 86_400_000;
    if (diffDays === 1) {
      out[out.length - 1] = entry;
    } else {
      out.push(entry);
    }
  }
  return out;
}

function dedupeAmavasyaEntries(entries) {
  const sorted = [...entries].sort((a, b) => a.date.localeCompare(b.date));
  const out = [];
  for (const entry of sorted) {
    if (out.length === 0) {
      out.push(entry);
      continue;
    }
    const previous = out[out.length - 1];
    const diffDays = (Date.parse(entry.date) - Date.parse(previous.date)) / 86_400_000;
    if (diffDays === 1) {
      continue;
    }
    out.push(entry);
  }
  return out;
}

async function fetchHtml(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status}`);
  }
  return response.text();
}

function parseLunarCards(html, year, kind) {
  const cardPattern =
    /dpEventDateTitle">([^<]+)<\/div>[\s\S]*?Begins - ([\s\S]*?)<\/div><div>Ends - ([\s\S]*?)<\/div>/g;
  const entries = [];
  let match;

  while ((match = cardPattern.exec(html))) {
    const date = parseGreg(match[1]);
    if (!date?.startsWith(String(year))) {
      continue;
    }

    const begins = parseTiming(stripHtml(match[2]), date);
    const ends = parseTiming(stripHtml(match[3]), date);
    if (!begins || !ends) {
      continue;
    }

    entries.push({ date, kind, begins, ends });
  }

  return kind === 'purnima' ? dedupePurnimaEntries(entries) : dedupeAmavasyaEntries(entries);
}

async function fetchLunarYear(year) {
  const [purnimaHtml, amavasyaHtml] = await Promise.all([
    fetchHtml(`https://www.drikpanchang.com/vrats/purnimasidates.html?year=${year}`),
    fetchHtml(`https://www.drikpanchang.com/vrats/amavasyadates.html?year=${year}`),
  ]);

  const purnima = parseLunarCards(purnimaHtml, year, 'purnima');
  const amavasya = parseLunarCards(amavasyaHtml, year, 'amavasya');

  return [...purnima, ...amavasya].sort((a, b) => a.date.localeCompare(b.date));
}

function emitFile(allYears) {
  const lines = [
    '/** Purnima & Amavasya dates/times for India (IST). Generated by scripts/generate-lunar-days.mjs */',
    '',
    "export type LunarDayKind = 'purnima' | 'amavasya';",
    '',
    'export type LunarTiming = {',
    '  date: string;',
    '  time: string;',
    '  label: string;',
    '};',
    '',
    'export type LunarDay = {',
    '  date: string;',
    '  kind: LunarDayKind;',
    '  begins: LunarTiming;',
    '  ends: LunarTiming;',
    '};',
    '',
  ];

  const allEntries = [];

  for (const [year, entries] of Object.entries(allYears)) {
    lines.push(`export const lunarDays${year}: LunarDay[] = ${JSON.stringify(entries, null, 2)};`, '');
    allEntries.push(`...lunarDays${year}`);
  }

  lines.push(
    `export const ALL_LUNAR_DAYS: LunarDay[] = [${allEntries.join(', ')}];`,
    '',
    'export const ALL_PURNIMA_DATES: string[] = ALL_LUNAR_DAYS.filter((day) => day.kind === "purnima").map((day) => day.date);',
    'export const ALL_AMAVASYA_DATES: string[] = ALL_LUNAR_DAYS.filter((day) => day.kind === "amavasya").map((day) => day.date);',
    '',
    'const LUNAR_BY_DATE = new Map(ALL_LUNAR_DAYS.map((day) => [day.date, day]));',
    '',
    'export function getLunarDayForDate(date: string): LunarDay | undefined {',
    '  return LUNAR_BY_DATE.get(date);',
    '}',
    '',
    'export function getLunarKindForDate(date: string): LunarDayKind | undefined {',
    '  return getLunarDayForDate(date)?.kind;',
    '}',
    '',
    'export function getLunarDaysForMonth(monthKey: string): LunarDay[] {',
    '  return ALL_LUNAR_DAYS.filter((day) => day.date.startsWith(monthKey)).sort((a, b) => a.date.localeCompare(b.date));',
    '}',
    '',
    'export function formatLunarTiming(timing: LunarTiming): string {',
    '  return timing.label;',
    '}',
    '',
  );

  writeFileSync(join(root, 'src/data/lunarDays.ts'), lines.join('\n'));
}

const allYears = {};

for (let year = START_YEAR; year <= END_YEAR; year += 1) {
  process.stdout.write(`Fetching lunar days ${year}…\n`);
  allYears[year] = await fetchLunarYear(year);
  const purnimaCount = allYears[year].filter((day) => day.kind === 'purnima').length;
  const amavasyaCount = allYears[year].filter((day) => day.kind === 'amavasya').length;
  process.stdout.write(`  ${purnimaCount} purnima, ${amavasyaCount} amavasya\n`);
}

emitFile(allYears);
console.log('Wrote src/data/lunarDays.ts');
